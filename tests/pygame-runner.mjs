import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext,Script} from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
new Script(read('pygame-runner.js'));
let listener,removed=0,messages=[],lastFrame;
const nodes={pygamePanel:{hidden:true},pygameFrameHost:{replaceChildren(frame){lastFrame=frame;}},closePygameBtn:{addEventListener(){}}};
const document={getElementById:id=>nodes[id],createElement:()=>({contentWindow:{postMessage:m=>messages.push(m)},remove(){removed++;}})};
const window={addEventListener:(name,fn)=>listener=fn};
runInNewContext(read('game-runner-host.js'),{window,document,location:{origin:'https://lab.test'},setTimeout:()=>1,clearTimeout(){}});
const host=window.pythonLabGameRunner;
assert.equal(host.modeFor('import pygame\n',{}),'pygame');
assert.equal(host.modeFor('import pgzrun\n',{}),'pgzero');
assert.equal(host.modeFor('from pgzero.builtins import Actor',{}),'pgzero');
assert.equal(host.modeFor('print(1)',{'unused.py':'import pygame'}),'python');
assert.equal(host.modeFor('import game',{'game.py':'import pgzrun'}),'pgzero');
assert.equal(host.modeFor('import game',{'game.py':'import game'}),'python');
assert.equal(host.modeFor('def draw(): pass',{},'pgzero'),'pgzero');
let done=0,outputs=[];
host.start({code:'import pygame',files:{},mode:'pygame'},{done:()=>done++,output:(...args)=>outputs.push(args)});
assert(!nodes.pygamePanel.hidden);
listener({source:{},origin:'https://lab.test',data:{channel:'python-lab-game',type:'ready'}});
assert.equal(messages.length,0,'Untrusted window must not receive project files');
listener({source:lastFrame.contentWindow,origin:'https://evil.test',data:{channel:'python-lab-game',type:'ready'}});
assert.equal(messages.length,0,'Untrusted origin must not receive project files');
listener({source:lastFrame.contentWindow,origin:'https://lab.test',data:{channel:'python-lab-game',type:'ready'}});
assert.equal(messages.length,1);
const old=lastFrame.contentWindow;
host.stop();assert.equal(removed,1);assert(nodes.pygamePanel.hidden);
listener({source:old,origin:'https://lab.test',data:{channel:'python-lab-game',type:'done'}});
assert.equal(done,0,'Stopped frame must not mutate current run state');
const galleryWindow={};runInNewContext(read('classroom-templates.js'),{window:galleryWindow,document:{getElementById:()=>null}});
for(const id of ['breakout','pgzero-starter'])for(const file of ['main.py','README.md'])assert.equal(galleryWindow.pythonLabTemplates.get(id).files[file],read('templates/'+id+'/'+file));
assert(read('app.js').includes("activeRun.purpose==='tests'?'python'"));
console.log('Pygame mode routing, iframe origin/source checks, Stop isolation and template parity passed.');
